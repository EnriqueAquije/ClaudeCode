DROP SCHEMA IF EXISTS caso03 CASCADE;
CREATE SCHEMA caso03;
SET search_path TO caso03;

-- =====================================================================================
-- 1. CATÁLOGOS
-- =====================================================================================

CREATE TABLE cat_moneda (
    moneda_cod  CHAR(3)     NOT NULL,
    moneda_desc VARCHAR(50) NOT NULL,
    CONSTRAINT pk_cat_moneda PRIMARY KEY (moneda_cod)
);

CREATE TABLE cat_marca (
    marca_cod  VARCHAR(10) NOT NULL,
    marca_desc VARCHAR(40) NOT NULL,
    CONSTRAINT pk_cat_marca PRIMARY KEY (marca_cod)
);

CREATE TABLE cat_estado_tarjeta (
    estado_tj_cod      VARCHAR(10) NOT NULL,
    estado_tj_desc     VARCHAR(50) NOT NULL,
    permite_consumo    BOOLEAN     NOT NULL,
    CONSTRAINT pk_cat_estado_tarjeta PRIMARY KEY (estado_tj_cod)
);

CREATE TABLE cat_tipo_transaccion (
    tipo_trx_cod    VARCHAR(10) NOT NULL,
    tipo_trx_desc   VARCHAR(60) NOT NULL,
    signo           SMALLINT    NOT NULL,   -- +1 aumenta la deuda, -1 la reduce
    es_consumo      BOOLEAN     NOT NULL,
    genera_cuotas   BOOLEAN     NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_cat_tipo_transaccion PRIMARY KEY (tipo_trx_cod),
    CONSTRAINT ck_cat_tipo_trx_signo   CHECK (signo IN (-1, 1))
);
COMMENT ON COLUMN cat_tipo_transaccion.signo IS
    'En tarjeta de crédito el saldo es DEUDA: el consumo suma (+1) y el pago resta (-1).';

CREATE TABLE cat_rubro (
    rubro_cod  VARCHAR(15) NOT NULL,
    rubro_desc VARCHAR(60) NOT NULL,
    CONSTRAINT pk_cat_rubro PRIMARY KEY (rubro_cod)
);

-- =====================================================================================
-- 2. ENTIDADES
-- =====================================================================================

CREATE TABLE titular (
    titular_id   BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    tipo_doc_cod CHAR(2)      NOT NULL,
    num_doc      VARCHAR(20)  NOT NULL,
    ape_paterno  VARCHAR(60)  NOT NULL,
    nombres      VARCHAR(80)  NOT NULL,
    fecha_alta   DATE         NOT NULL,
    CONSTRAINT pk_titular     PRIMARY KEY (titular_id),
    CONSTRAINT uq_titular_doc UNIQUE (tipo_doc_cod, num_doc)
);

CREATE TABLE cuenta_tarjeta (
    cuenta_tj_id      BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    num_cuenta_tj     VARCHAR(20)   NOT NULL,
    titular_id        BIGINT        NOT NULL,
    marca_cod         VARCHAR(10)   NOT NULL,
    moneda_cod        CHAR(3)       NOT NULL,
    estado_tj_cod     VARCHAR(10)   NOT NULL,
    dia_facturacion   SMALLINT      NOT NULL,
    linea_aprobada    NUMERIC(18,2) NOT NULL,
    tea_revolvente    NUMERIC(9,6)  NOT NULL,
    tea_cuotas        NUMERIC(9,6)  NOT NULL,
    fecha_apertura    DATE          NOT NULL,
    CONSTRAINT pk_cuenta_tj        PRIMARY KEY (cuenta_tj_id),
    CONSTRAINT uq_cuenta_tj_num    UNIQUE (num_cuenta_tj),
    CONSTRAINT fk_cuenta_tj_titular FOREIGN KEY (titular_id)    REFERENCES titular (titular_id),
    CONSTRAINT fk_cuenta_tj_marca  FOREIGN KEY (marca_cod)     REFERENCES cat_marca (marca_cod),
    CONSTRAINT fk_cuenta_tj_moneda FOREIGN KEY (moneda_cod)    REFERENCES cat_moneda (moneda_cod),
    CONSTRAINT fk_cuenta_tj_estado FOREIGN KEY (estado_tj_cod) REFERENCES cat_estado_tarjeta (estado_tj_cod),
    CONSTRAINT ck_cuenta_tj_dia    CHECK (dia_facturacion BETWEEN 1 AND 28),
    CONSTRAINT ck_cuenta_tj_linea  CHECK (linea_aprobada > 0),
    CONSTRAINT ck_cuenta_tj_tea    CHECK (tea_revolvente > 0 AND tea_cuotas > 0)
);
COMMENT ON COLUMN cuenta_tarjeta.dia_facturacion IS
    'Máximo 28: evita el problema de los meses de 29, 30 y 31 días.';

-- Una cuenta de tarjeta puede tener varios plásticos (titular y adicionales).
CREATE TABLE plastico (
    plastico_id     BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    cuenta_tj_id    BIGINT       NOT NULL,
    num_plastico_enmasc CHAR(19) NOT NULL,
    tipo_plastico   VARCHAR(12)  NOT NULL,
    nombre_impreso  VARCHAR(60)  NOT NULL,
    fecha_emision   DATE         NOT NULL,
    fecha_expiracion DATE        NOT NULL,
    esta_activo     BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_plastico        PRIMARY KEY (plastico_id),
    CONSTRAINT uq_plastico_num    UNIQUE (num_plastico_enmasc),
    CONSTRAINT fk_plastico_cuenta FOREIGN KEY (cuenta_tj_id) REFERENCES cuenta_tarjeta (cuenta_tj_id),
    CONSTRAINT ck_plastico_tipo   CHECK (tipo_plastico IN ('TITULAR','ADICIONAL')),
    CONSTRAINT ck_plastico_fechas CHECK (fecha_expiracion > fecha_emision)
);
COMMENT ON COLUMN plastico.num_plastico_enmasc IS
    'SOLO enmascarado (411111******1111). El PAN completo NUNCA se almacena en este modelo.';

-- Un solo plástico TITULAR activo por cuenta.
CREATE UNIQUE INDEX uq_plastico_titular_activo
    ON plastico (cuenta_tj_id)
    WHERE tipo_plastico = 'TITULAR' AND esta_activo;

-- Historia de la línea de crédito (SCD2): sin esto no se puede auditar un sobregiro.
CREATE TABLE linea_credito_hist (
    cuenta_tj_id  BIGINT        NOT NULL,
    fecha_desde   DATE          NOT NULL,
    fecha_hasta   DATE          NOT NULL DEFAULT DATE '9999-12-31',
    linea_anterior NUMERIC(18,2),
    linea_nueva   NUMERIC(18,2) NOT NULL,
    motivo        VARCHAR(40)   NOT NULL,
    CONSTRAINT pk_linea_hist      PRIMARY KEY (cuenta_tj_id, fecha_desde),
    CONSTRAINT fk_linea_hist_cta  FOREIGN KEY (cuenta_tj_id) REFERENCES cuenta_tarjeta (cuenta_tj_id),
    CONSTRAINT ck_linea_hist_vig  CHECK (fecha_hasta >= fecha_desde),
    CONSTRAINT ck_linea_hist_val  CHECK (linea_nueva > 0)
);

CREATE TABLE ciclo_facturacion (
    cuenta_tj_id      BIGINT  NOT NULL,
    periodo           CHAR(6) NOT NULL,
    fecha_inicio      DATE    NOT NULL,
    fecha_cierre      DATE    NOT NULL,
    fecha_vencimiento DATE    NOT NULL,
    CONSTRAINT pk_ciclo        PRIMARY KEY (cuenta_tj_id, periodo),
    CONSTRAINT fk_ciclo_cuenta FOREIGN KEY (cuenta_tj_id) REFERENCES cuenta_tarjeta (cuenta_tj_id),
    CONSTRAINT ck_ciclo_fechas CHECK (fecha_cierre >= fecha_inicio AND fecha_vencimiento > fecha_cierre),
    CONSTRAINT ck_ciclo_per    CHECK (periodo ~ '^[0-9]{6}$')
);
COMMENT ON TABLE ciclo_facturacion IS
    'El ciclo NO es el mes calendario: depende del dia_facturacion de cada cuenta.';

CREATE TABLE transaccion (
    transaccion_id  BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    cuenta_tj_id    BIGINT        NOT NULL,
    plastico_id     BIGINT,
    num_operacion   VARCHAR(30)   NOT NULL,
    fecha_operacion TIMESTAMP     NOT NULL,
    fecha_proceso   DATE          NOT NULL,
    periodo_cargo   CHAR(6)       NOT NULL,
    tipo_trx_cod    VARCHAR(10)   NOT NULL,
    rubro_cod       VARCHAR(15),
    comercio        VARCHAR(80),
    moneda_cod      CHAR(3)       NOT NULL,
    monto           NUMERIC(18,2) NOT NULL,
    monto_con_signo NUMERIC(18,2) NOT NULL,
    num_cuotas      SMALLINT      NOT NULL DEFAULT 1,
    CONSTRAINT pk_transaccion        PRIMARY KEY (transaccion_id),
    CONSTRAINT uq_transaccion_oper   UNIQUE (num_operacion),
    CONSTRAINT fk_transaccion_cuenta FOREIGN KEY (cuenta_tj_id) REFERENCES cuenta_tarjeta (cuenta_tj_id),
    CONSTRAINT fk_transaccion_plast  FOREIGN KEY (plastico_id)  REFERENCES plastico (plastico_id),
    CONSTRAINT fk_transaccion_tipo   FOREIGN KEY (tipo_trx_cod) REFERENCES cat_tipo_transaccion (tipo_trx_cod),
    CONSTRAINT fk_transaccion_rubro  FOREIGN KEY (rubro_cod)    REFERENCES cat_rubro (rubro_cod),
    CONSTRAINT fk_transaccion_moneda FOREIGN KEY (moneda_cod)   REFERENCES cat_moneda (moneda_cod),
    CONSTRAINT ck_transaccion_monto  CHECK (monto > 0),
    CONSTRAINT ck_transaccion_signo  CHECK (ABS(monto_con_signo) = monto),
    CONSTRAINT ck_transaccion_cuotas CHECK (num_cuotas BETWEEN 1 AND 36)
);
COMMENT ON COLUMN transaccion.periodo_cargo IS
    'Ciclo al que se imputa. Una compra del dia 30 puede caer en el ciclo siguiente.';

-- Plan de cuotas de una compra fraccionada.
CREATE TABLE transaccion_cuota (
    transaccion_id BIGINT        NOT NULL,
    num_cuota      SMALLINT      NOT NULL,
    periodo_cargo  CHAR(6)       NOT NULL,
    monto_capital  NUMERIC(18,2) NOT NULL,
    monto_interes  NUMERIC(18,2) NOT NULL DEFAULT 0,
    monto_cuota    NUMERIC(18,2) NOT NULL,
    CONSTRAINT pk_transaccion_cuota  PRIMARY KEY (transaccion_id, num_cuota),
    CONSTRAINT fk_transaccion_cuota  FOREIGN KEY (transaccion_id) REFERENCES transaccion (transaccion_id),
    CONSTRAINT ck_transaccion_cuota  CHECK (monto_cuota = monto_capital + monto_interes),
    CONSTRAINT ck_transaccion_cuota_n CHECK (num_cuota > 0)
);
COMMENT ON TABLE transaccion_cuota IS
    'Compra en cuotas: caracteristica central del mercado peruano de tarjetas.';

CREATE TABLE estado_cuenta (
    cuenta_tj_id      BIGINT        NOT NULL,
    periodo           CHAR(6)       NOT NULL,
    fecha_cierre      DATE          NOT NULL,
    fecha_vencimiento DATE          NOT NULL,
    saldo_anterior    NUMERIC(18,2) NOT NULL,
    total_consumos    NUMERIC(18,2) NOT NULL,
    total_cargos      NUMERIC(18,2) NOT NULL,
    total_pagos       NUMERIC(18,2) NOT NULL,
    saldo_actual      NUMERIC(18,2) NOT NULL,
    pago_minimo       NUMERIC(18,2) NOT NULL,
    linea_aprobada    NUMERIC(18,2) NOT NULL,
    linea_disponible  NUMERIC(18,2) NOT NULL,
    fecha_pago        DATE,
    monto_pagado      NUMERIC(18,2) NOT NULL DEFAULT 0,
    dias_atraso       INTEGER       NOT NULL DEFAULT 0,
    CONSTRAINT pk_estado_cuenta      PRIMARY KEY (cuenta_tj_id, periodo),
    CONSTRAINT fk_estado_cuenta_ctj  FOREIGN KEY (cuenta_tj_id)          REFERENCES cuenta_tarjeta (cuenta_tj_id),
    CONSTRAINT fk_estado_cuenta_cic  FOREIGN KEY (cuenta_tj_id, periodo) REFERENCES ciclo_facturacion (cuenta_tj_id, periodo),
    -- LA REGLA CENTRAL DEL CASO: el estado de cuenta debe cuadrar por construcción.
    CONSTRAINT ck_estado_cuenta_cuadre CHECK (
        saldo_actual = saldo_anterior + total_consumos + total_cargos - total_pagos),
    CONSTRAINT ck_estado_cuenta_minimo CHECK (pago_minimo >= 0 AND pago_minimo <= GREATEST(saldo_actual, 0)),
    CONSTRAINT ck_estado_cuenta_atraso CHECK (dias_atraso >= 0)
);
COMMENT ON CONSTRAINT ck_estado_cuenta_cuadre ON estado_cuenta IS
    'Un estado de cuenta que no cuadra es un reclamo del cliente y un hallazgo de auditoria.';

