-- 4. VISTAS
-- =====================================================================================

CREATE VIEW vw_utilizacion_linea AS
SELECT  ec.cuenta_tj_id,
        ec.periodo,
        ct.marca_cod,
        ec.linea_aprobada,
        ec.saldo_actual,
        ROUND(100.0 * ec.saldo_actual / NULLIF(ec.linea_aprobada, 0), 2) AS pct_utilizacion,
        ec.pago_minimo,
        ec.monto_pagado,
        CASE
            WHEN ec.monto_pagado >= ec.saldo_actual AND ec.saldo_actual > 0 THEN 'PAGADOR_TOTAL'
            WHEN ec.monto_pagado >= ec.pago_minimo  AND ec.pago_minimo > 0  THEN 'REVOLVENTE'
            WHEN ec.saldo_actual <= 0                                       THEN 'SIN_DEUDA'
            ELSE 'INCUMPLIDO'
        END AS perfil_pago
FROM    estado_cuenta  ec
JOIN    cuenta_tarjeta ct ON ct.cuenta_tj_id = ec.cuenta_tj_id;

COMMENT ON VIEW vw_utilizacion_linea IS
    'Segmentacion de comportamiento de pago: pagador total, revolvente o incumplido.';
