-- =====================================================================================
-- 5. VISTA DE CONSUMO (columnas explícitas, nunca SELECT *)
-- =====================================================================================

CREATE VIEW vw_cuenta_detalle AS
SELECT  c.cuenta_id,
        c.num_cuenta,
        c.cci,
        p.producto_cod,
        p.producto_nombre,
        p.familia_cod,
        c.moneda_cod,
        c.estado_cta_cod,
        c.fecha_apertura,
        c.saldo_contable,
        c.saldo_retenido,
        c.saldo_disponible,
        o.oficina_cod,
        o.oficina_nombre,
        u.departamento,
        u.provincia,
        u.distrito,
        cl.cliente_id       AS titular_cliente_id,
        cl.tipo_doc_cod     AS titular_tipo_doc,
        cl.num_doc          AS titular_num_doc,
        cl.ape_paterno || ' ' || COALESCE(cl.ape_materno,'') || ', ' || cl.nombres AS titular_nombre
FROM        cuenta          c
JOIN        producto        p  ON p.producto_id = c.producto_id
JOIN        oficina         o  ON o.oficina_id  = c.oficina_id
JOIN        cat_ubigeo      u  ON u.ubigeo      = o.ubigeo
LEFT JOIN   cuenta_titular  ct ON ct.cuenta_id  = c.cuenta_id
                              AND ct.rol_cod    = 'TITULAR'
                              AND ct.fecha_hasta IS NULL
LEFT JOIN   cliente         cl ON cl.cliente_id = ct.cliente_id;

COMMENT ON VIEW vw_cuenta_detalle IS 'Vista operativa de cuenta con su titular principal vigente.';

-- Vista enmascarada para ambientes NO productivos (Ley 29733).
CREATE VIEW vw_cuenta_detalle_anonimizada AS
SELECT  cuenta_id,
        'XXXX' || RIGHT(num_cuenta, 4)      AS num_cuenta,
        producto_cod,
        producto_nombre,
        familia_cod,
        moneda_cod,
        estado_cta_cod,
        fecha_apertura,
        saldo_contable,
        departamento,
        provincia,
        REPEAT('*', GREATEST(LENGTH(titular_num_doc) - 3, 0)) || RIGHT(titular_num_doc, 3) AS titular_num_doc,
        LEFT(titular_nombre, 1) || '***'    AS titular_nombre
FROM vw_cuenta_detalle;

COMMENT ON VIEW vw_cuenta_detalle_anonimizada IS
    'Uso obligatorio en desarrollo/QA: enmascara documento y nombre (Ley 29733).';
