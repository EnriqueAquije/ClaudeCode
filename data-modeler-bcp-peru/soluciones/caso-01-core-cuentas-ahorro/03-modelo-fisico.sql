-- =====================================================================================
-- 1. CATÁLOGOS (dominios cerrados)
--    Regla: todo dominio regulado o estable vive en catálogo, nunca como texto libre.
-- =====================================================================================

CREATE TABLE cat_moneda (
    moneda_cod      CHAR(3)         NOT NULL,
    moneda_desc     VARCHAR(50)     NOT NULL,
    simbolo         VARCHAR(5)      NOT NULL,
    es_vigente      BOOLEAN         NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_cat_moneda PRIMARY KEY (moneda_cod)
);
COMMENT ON TABLE cat_moneda IS 'Monedas ISO 4217 operadas por la entidad.';

CREATE TABLE cat_tipo_documento (
    tipo_doc_cod        CHAR(2)     NOT NULL,
    tipo_doc_desc       VARCHAR(40) NOT NULL,
    longitud_esperada   SMALLINT,
    es_persona_juridica BOOLEAN     NOT NULL DEFAULT FALSE,
    es_vigente          BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_cat_tipo_documento PRIMARY KEY (tipo_doc_cod)
);
COMMENT ON TABLE cat_tipo_documento IS 'Tipos de documento de identidad aceptados (dominio regulado SBS).';

CREATE TABLE cat_ubigeo (
    ubigeo          CHAR(6)         NOT NULL,
    departamento    VARCHAR(40)     NOT NULL,
    provincia       VARCHAR(40)     NOT NULL,
    distrito        VARCHAR(40)     NOT NULL,
    CONSTRAINT pk_cat_ubigeo PRIMARY KEY (ubigeo)
);
COMMENT ON TABLE cat_ubigeo IS 'Ubigeo INEI: departamento(2)+provincia(2)+distrito(2). Llave NATURAL.';
COMMENT ON COLUMN cat_ubigeo.ubigeo IS 'CHAR(6): los ceros a la izquierda son significativos. Nunca INTEGER.';

CREATE TABLE cat_canal (
    canal_cod       VARCHAR(10)     NOT NULL,
    canal_desc      VARCHAR(50)     NOT NULL,
    es_presencial   BOOLEAN         NOT NULL,
    es_cliente      BOOLEAN         NOT NULL DEFAULT TRUE,   -- FALSE = originado por el banco
    es_vigente      BOOLEAN         NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_cat_canal PRIMARY KEY (canal_cod)
);
COMMENT ON COLUMN cat_canal.es_cliente IS 'TRUE si la operación la origina el cliente; FALSE si la origina el banco (batch).';

CREATE TABLE cat_estado_cuenta (
    estado_cta_cod      VARCHAR(10) NOT NULL,
    estado_cta_desc     VARCHAR(50) NOT NULL,
    permite_movimiento  BOOLEAN     NOT NULL,
    es_final            BOOLEAN     NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_cat_estado_cuenta PRIMARY KEY (estado_cta_cod)
);

CREATE TABLE cat_tipo_movimiento (
    tipo_mov_cod        VARCHAR(10)     NOT NULL,
    tipo_mov_desc       VARCHAR(60)     NOT NULL,
    signo               SMALLINT        NOT NULL,
    es_operacion_cliente BOOLEAN        NOT NULL DEFAULT TRUE,
    cuenta_contable     CHAR(6),
    es_vigente          BOOLEAN         NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_cat_tipo_movimiento PRIMARY KEY (tipo_mov_cod),
    CONSTRAINT ck_cat_tipo_mov_signo  CHECK (signo IN (-1, 1))
);
COMMENT ON COLUMN cat_tipo_movimiento.signo IS
    'ADR-03: el signo vive en el catálogo, no en el monto. El monto siempre es positivo.';
COMMENT ON COLUMN cat_tipo_movimiento.cuenta_contable IS
    'Mapeo al Manual de Contabilidad SBS: permite el cuadre contable.';

-- =====================================================================================
-- 2. ENTIDADES MAESTRAS
-- =====================================================================================

CREATE TABLE oficina (
    oficina_id      INTEGER         GENERATED BY DEFAULT AS IDENTITY,
    oficina_cod     VARCHAR(10)     NOT NULL,
    oficina_nombre  VARCHAR(80)     NOT NULL,
    ubigeo          CHAR(6)         NOT NULL,
    fecha_apertura  DATE            NOT NULL,
    es_vigente      BOOLEAN         NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_oficina        PRIMARY KEY (oficina_id),
    CONSTRAINT uq_oficina_cod    UNIQUE (oficina_cod),
    CONSTRAINT fk_oficina_ubigeo FOREIGN KEY (ubigeo) REFERENCES cat_ubigeo (ubigeo)
);

CREATE TABLE producto (
    producto_id         INTEGER         GENERATED BY DEFAULT AS IDENTITY,
    producto_cod        VARCHAR(15)     NOT NULL,
    producto_nombre     VARCHAR(80)     NOT NULL,
    familia_cod         VARCHAR(20)     NOT NULL,
    moneda_cod          CHAR(3)         NOT NULL,
    monto_apertura_min  NUMERIC(18,2)   NOT NULL DEFAULT 0,
    trea_pct            NUMERIC(9,6)    NOT NULL DEFAULT 0,
    permite_saldo_negativo BOOLEAN      NOT NULL DEFAULT FALSE,
    es_vigente          BOOLEAN         NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_producto          PRIMARY KEY (producto_id),
    CONSTRAINT uq_producto_cod      UNIQUE (producto_cod),
    CONSTRAINT fk_producto_moneda   FOREIGN KEY (moneda_cod) REFERENCES cat_moneda (moneda_cod),
    CONSTRAINT ck_producto_familia  CHECK (familia_cod IN ('AHORRO','SUELDO','CTS','CORRIENTE','PLAZO')),
    CONSTRAINT ck_producto_trea     CHECK (trea_pct >= 0 AND trea_pct <= 1),
    CONSTRAINT ck_producto_apertura CHECK (monto_apertura_min >= 0)
);
COMMENT ON COLUMN producto.trea_pct IS 'TREA expresada como fracción (0.0125 = 1.25%).';

CREATE TABLE cliente (
    cliente_id          BIGINT          GENERATED BY DEFAULT AS IDENTITY,
    tipo_doc_cod        CHAR(2)         NOT NULL,
    num_doc             VARCHAR(20)     NOT NULL,
    ape_paterno         VARCHAR(60)     NOT NULL,
    ape_materno         VARCHAR(60),
    nombres             VARCHAR(80)     NOT NULL,
    fecha_nacimiento    DATE,
    ubigeo              CHAR(6),
    fecha_alta          DATE            NOT NULL,
    es_vigente          BOOLEAN         NOT NULL DEFAULT TRUE,
    fecha_hora_creacion TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    usuario_creacion    VARCHAR(50)     NOT NULL DEFAULT CURRENT_USER,
    CONSTRAINT pk_cliente           PRIMARY KEY (cliente_id),
    CONSTRAINT uq_cliente_doc       UNIQUE (tipo_doc_cod, num_doc),
    CONSTRAINT fk_cliente_tipo_doc  FOREIGN KEY (tipo_doc_cod) REFERENCES cat_tipo_documento (tipo_doc_cod),
    CONSTRAINT fk_cliente_ubigeo    FOREIGN KEY (ubigeo)       REFERENCES cat_ubigeo (ubigeo),
    CONSTRAINT ck_cliente_nacimiento CHECK (fecha_nacimiento IS NULL OR fecha_nacimiento < fecha_alta),
    CONSTRAINT ck_cliente_num_doc   CHECK (num_doc ~ '^[A-Z0-9]+$')
);
COMMENT ON TABLE  cliente IS 'Persona natural o jurídica con relación comercial. CONTIENE DATOS PERSONALES.';
COMMENT ON COLUMN cliente.cliente_id IS 'ADR-01: llave sustituta. El documento NO es PK (Ley 29733: derecho de cancelación).';
COMMENT ON COLUMN cliente.num_doc IS 'DATO PERSONAL (Ley 29733). VARCHAR: conserva ceros a la izquierda.';

-- =====================================================================================
-- 3. ENTIDADES OPERATIVAS
-- =====================================================================================

CREATE TABLE cuenta (
    cuenta_id           BIGINT          GENERATED BY DEFAULT AS IDENTITY,
    num_cuenta          VARCHAR(20)     NOT NULL,
    cci                 CHAR(20)        NOT NULL,
    producto_id         INTEGER         NOT NULL,
    moneda_cod          CHAR(3)         NOT NULL,
    oficina_id          INTEGER         NOT NULL,
    estado_cta_cod      VARCHAR(10)     NOT NULL,
    fecha_apertura      DATE            NOT NULL,
    fecha_cierre        DATE,
    saldo_contable      NUMERIC(18,2)   NOT NULL DEFAULT 0,
    saldo_retenido      NUMERIC(18,2)   NOT NULL DEFAULT 0,
    -- RN-11: el saldo disponible es DERIVADO. Una sola fuente de verdad.
    saldo_disponible    NUMERIC(18,2)   GENERATED ALWAYS AS (saldo_contable - saldo_retenido) STORED,
    fecha_hora_creacion TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_cuenta            PRIMARY KEY (cuenta_id),
    CONSTRAINT uq_cuenta_numero     UNIQUE (num_cuenta),
    CONSTRAINT uq_cuenta_cci        UNIQUE (cci),
    CONSTRAINT fk_cuenta_producto   FOREIGN KEY (producto_id)    REFERENCES producto (producto_id),
    CONSTRAINT fk_cuenta_moneda     FOREIGN KEY (moneda_cod)     REFERENCES cat_moneda (moneda_cod),
    CONSTRAINT fk_cuenta_oficina    FOREIGN KEY (oficina_id)     REFERENCES oficina (oficina_id),
    CONSTRAINT fk_cuenta_estado     FOREIGN KEY (estado_cta_cod) REFERENCES cat_estado_cuenta (estado_cta_cod),
    CONSTRAINT ck_cuenta_cierre     CHECK (fecha_cierre IS NULL OR fecha_cierre >= fecha_apertura),
    CONSTRAINT ck_cuenta_retenido   CHECK (saldo_retenido >= 0),
    CONSTRAINT ck_cuenta_cci_fmt    CHECK (cci ~ '^[0-9]{20}$')
);
COMMENT ON COLUMN cuenta.saldo_disponible IS 'ADR-02: columna GENERADA. Nunca se actualiza a mano.';
COMMENT ON COLUMN cuenta.saldo_contable IS 'Debe cuadrar siempre con SUM(movimiento.monto_con_signo). Ver CAL-04.';

-- RN-02 / RN-03: relación N:M entre cliente y cuenta, con rol y vigencia.
CREATE TABLE cuenta_titular (
    cuenta_id       BIGINT          NOT NULL,
    cliente_id      BIGINT          NOT NULL,
    rol_cod         VARCHAR(15)     NOT NULL,
    fecha_desde     DATE            NOT NULL,
    fecha_hasta     DATE,
    CONSTRAINT pk_cuenta_titular      PRIMARY KEY (cuenta_id, cliente_id, fecha_desde),
    CONSTRAINT fk_cuenta_titular_cta  FOREIGN KEY (cuenta_id)  REFERENCES cuenta (cuenta_id),
    CONSTRAINT fk_cuenta_titular_cli  FOREIGN KEY (cliente_id) REFERENCES cliente (cliente_id),
    CONSTRAINT ck_cuenta_titular_rol  CHECK (rol_cod IN ('TITULAR','MANCOMUNADO','APODERADO')),
    CONSTRAINT ck_cuenta_titular_vig  CHECK (fecha_hasta IS NULL OR fecha_hasta >= fecha_desde)
);
COMMENT ON TABLE cuenta_titular IS 'Relación N:M cliente-cuenta. Soporta cuentas mancomunadas (RN-03).';

-- RN-03: exactamente UN titular principal vigente por cuenta.
-- Un índice único parcial es la forma declarativa de imponer esta regla.
CREATE UNIQUE INDEX uq_cuenta_titular_principal
    ON cuenta_titular (cuenta_id)
    WHERE rol_cod = 'TITULAR' AND fecha_hasta IS NULL;

CREATE TABLE movimiento (
    movimiento_id           BIGINT          GENERATED BY DEFAULT AS IDENTITY,
    cuenta_id               BIGINT          NOT NULL,
    num_operacion           VARCHAR(30)     NOT NULL,
    fecha_operacion         TIMESTAMP       NOT NULL,
    fecha_contable          DATE            NOT NULL,
    tipo_mov_cod            VARCHAR(10)     NOT NULL,
    canal_cod               VARCHAR(10)     NOT NULL,
    oficina_id              INTEGER,
    moneda_cod              CHAR(3)         NOT NULL,
    monto                   NUMERIC(18,2)   NOT NULL,
    monto_con_signo         NUMERIC(18,2)   NOT NULL,
    saldo_posterior         NUMERIC(18,2)   NOT NULL,
    glosa                   VARCHAR(140),
    es_extorno              BOOLEAN         NOT NULL DEFAULT FALSE,
    movimiento_extornado_id BIGINT,
    fecha_hora_creacion     TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_movimiento              PRIMARY KEY (movimiento_id),
    CONSTRAINT uq_movimiento_operacion    UNIQUE (num_operacion),
    CONSTRAINT fk_movimiento_cuenta       FOREIGN KEY (cuenta_id)   REFERENCES cuenta (cuenta_id),
    CONSTRAINT fk_movimiento_tipo         FOREIGN KEY (tipo_mov_cod) REFERENCES cat_tipo_movimiento (tipo_mov_cod),
    CONSTRAINT fk_movimiento_canal        FOREIGN KEY (canal_cod)   REFERENCES cat_canal (canal_cod),
    CONSTRAINT fk_movimiento_oficina      FOREIGN KEY (oficina_id)  REFERENCES oficina (oficina_id),
    CONSTRAINT fk_movimiento_moneda       FOREIGN KEY (moneda_cod)  REFERENCES cat_moneda (moneda_cod),
    CONSTRAINT fk_movimiento_extorno      FOREIGN KEY (movimiento_extornado_id) REFERENCES movimiento (movimiento_id),
    CONSTRAINT ck_movimiento_monto_positivo CHECK (monto > 0),
    CONSTRAINT ck_movimiento_signo        CHECK (ABS(monto_con_signo) = monto),
    CONSTRAINT ck_movimiento_fechas       CHECK (fecha_contable >= fecha_operacion::DATE),
    CONSTRAINT ck_movimiento_extorno      CHECK (
        (es_extorno = FALSE AND movimiento_extornado_id IS NULL)
     OR (es_extorno = TRUE  AND movimiento_extornado_id IS NOT NULL))
);
COMMENT ON TABLE  movimiento IS 'Movimiento individual de una cuenta. Grano: un evento. NUNCA se borra (RN-12).';
COMMENT ON COLUMN movimiento.monto IS 'Siempre POSITIVO. El sentido lo da cat_tipo_movimiento.signo.';
COMMENT ON COLUMN movimiento.num_operacion IS 'Único en todo el banco: evita doble contabilización (RN-13).';
COMMENT ON COLUMN movimiento.fecha_operacion IS 'Cuándo ocurrió (con hora).';
COMMENT ON COLUMN movimiento.fecha_contable IS 'A qué día se imputa contablemente. Puede diferir de la operación.';

