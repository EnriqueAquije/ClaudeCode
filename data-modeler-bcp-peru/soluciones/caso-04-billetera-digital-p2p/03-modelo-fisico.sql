-- =====================================================================================
-- CASO 04 - Billetera digital P2P: alto volumen, particionamiento e idempotencia
-- Modelo FÍSICO - PostgreSQL 14+
-- =====================================================================================
-- Este caso introduce PARTICIONAMIENTO DECLARATIVO. Consecuencias que enseña:
--   (a) la llave primaria de una tabla particionada DEBE incluir la clave de partición;
--   (b) por lo mismo, un UNIQUE global no es posible sobre la tabla particionada;
--   (c) la unicidad global (idempotencia) se resuelve con una tabla auxiliar NO particionada.
-- =====================================================================================

DROP SCHEMA IF EXISTS caso04 CASCADE;
CREATE SCHEMA caso04;
SET search_path TO caso04;

-- =====================================================================================
-- 1. CATÁLOGOS
-- =====================================================================================

CREATE TABLE cat_moneda (
    moneda_cod  CHAR(3)     NOT NULL,
    moneda_desc VARCHAR(50) NOT NULL,
    CONSTRAINT pk_cat_moneda PRIMARY KEY (moneda_cod)
);

CREATE TABLE cat_estado_transferencia (
    estado_cod  VARCHAR(12) NOT NULL,
    estado_desc VARCHAR(50) NOT NULL,
    es_final    BOOLEAN     NOT NULL,
    es_exitoso  BOOLEAN     NOT NULL,
    CONSTRAINT pk_cat_estado_transf PRIMARY KEY (estado_cod)
);

CREATE TABLE cat_motivo_rechazo (
    motivo_cod  VARCHAR(20) NOT NULL,
    motivo_desc VARCHAR(80) NOT NULL,
    es_del_usuario BOOLEAN  NOT NULL,
    CONSTRAINT pk_cat_motivo_rechazo PRIMARY KEY (motivo_cod)
);

CREATE TABLE cat_tipo_operacion (
    tipo_op_cod  VARCHAR(12) NOT NULL,
    tipo_op_desc VARCHAR(60) NOT NULL,
    signo        SMALLINT    NOT NULL,
    CONSTRAINT pk_cat_tipo_operacion PRIMARY KEY (tipo_op_cod),
    CONSTRAINT ck_cat_tipo_op_signo  CHECK (signo IN (-1, 1))
);

-- =====================================================================================
-- 2. USUARIOS Y DISPOSITIVOS
-- =====================================================================================

CREATE TABLE usuario_billetera (
    usuario_id       BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    num_celular      CHAR(9)      NOT NULL,
    tipo_doc_cod     CHAR(2)      NOT NULL,
    num_doc          VARCHAR(20)  NOT NULL,
    nombre_mostrado  VARCHAR(60)  NOT NULL,
    es_negocio       BOOLEAN      NOT NULL DEFAULT FALSE,
    cuenta_vinculada VARCHAR(20),
    estado_usuario   VARCHAR(10)  NOT NULL,
    fecha_alta       DATE         NOT NULL,
    ubigeo           CHAR(6),
    CONSTRAINT pk_usuario_billetera  PRIMARY KEY (usuario_id),
    CONSTRAINT uq_usuario_celular    UNIQUE (num_celular),
    CONSTRAINT uq_usuario_doc        UNIQUE (tipo_doc_cod, num_doc),
    CONSTRAINT ck_usuario_celular    CHECK (num_celular ~ '^9[0-9]{8}$'),
    CONSTRAINT ck_usuario_estado     CHECK (estado_usuario IN ('ACTIVO','SUSPENDIDO','BAJA'))
);
COMMENT ON COLUMN usuario_billetera.num_celular IS
    'Identificador de negocio de la billetera. CHAR(9): en Peru los moviles empiezan con 9.';
COMMENT ON COLUMN usuario_billetera.num_doc IS 'DATO PERSONAL (Ley 29733).';

CREATE TABLE dispositivo (
    dispositivo_id   BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    usuario_id       BIGINT       NOT NULL,
    id_dispositivo   VARCHAR(64)  NOT NULL,
    sistema_operativo VARCHAR(20) NOT NULL,
    version_app      VARCHAR(15)  NOT NULL,
    fecha_registro   TIMESTAMP    NOT NULL,
    esta_activo      BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_dispositivo      PRIMARY KEY (dispositivo_id),
    CONSTRAINT uq_dispositivo_id   UNIQUE (id_dispositivo),
    CONSTRAINT fk_dispositivo_usr  FOREIGN KEY (usuario_id) REFERENCES usuario_billetera (usuario_id),
    CONSTRAINT ck_dispositivo_so   CHECK (sistema_operativo IN ('ANDROID','IOS','WEB'))
);

-- Regla antifraude: un solo dispositivo activo por usuario.
CREATE UNIQUE INDEX uq_dispositivo_activo
    ON dispositivo (usuario_id) WHERE esta_activo;

-- =====================================================================================
-- 3. PARÁMETROS DE LÍMITES (vigentes por fecha)
-- =====================================================================================

CREATE TABLE par_limite (
    segmento_cod       VARCHAR(15)   NOT NULL,
    monto_max_operacion NUMERIC(18,2) NOT NULL,
    monto_max_dia      NUMERIC(18,2) NOT NULL,
    num_max_dia        INTEGER       NOT NULL,
    fecha_desde        DATE          NOT NULL,
    fecha_hasta        DATE          NOT NULL DEFAULT DATE '9999-12-31',
    base_legal         VARCHAR(120),
    CONSTRAINT pk_par_limite    PRIMARY KEY (segmento_cod, fecha_desde),
    CONSTRAINT ck_par_limite_op CHECK (monto_max_operacion > 0 AND monto_max_dia >= monto_max_operacion),
    CONSTRAINT ck_par_limite_n  CHECK (num_max_dia > 0)
);
COMMENT ON TABLE par_limite IS
    'Limites operativos y de PLAFT. Parametrizados por fecha: cambian por politica y por norma.';

-- =====================================================================================
-- 4. TABLA DE IDEMPOTENCIA (NO particionada)
--    Resuelve el problema central del alto volumen móvil: la app reintenta cuando la red
--    falla. Sin esto, un reintento genera una segunda transferencia y un doble cargo.
-- =====================================================================================

CREATE TABLE idempotencia (
    clave_idempotencia VARCHAR(64) NOT NULL,
    usuario_id         BIGINT      NOT NULL,
    fecha_hora_registro TIMESTAMP  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    transferencia_id   BIGINT      NOT NULL,
    fecha_operacion    TIMESTAMP   NOT NULL,
    CONSTRAINT pk_idempotencia     PRIMARY KEY (clave_idempotencia),
    CONSTRAINT fk_idempotencia_usr FOREIGN KEY (usuario_id) REFERENCES usuario_billetera (usuario_id)
);
COMMENT ON TABLE idempotencia IS
    'Unicidad GLOBAL de la clave de idempotencia. Va aparte porque una tabla particionada '
    'no admite UNIQUE que no incluya la clave de particion.';

-- =====================================================================================
-- 5. TRANSFERENCIAS (TABLA PARTICIONADA POR RANGO DE FECHA)
-- =====================================================================================

CREATE TABLE transferencia (
    transferencia_id    BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    fecha_operacion     TIMESTAMP     NOT NULL,
    usuario_origen_id   BIGINT        NOT NULL,
    usuario_destino_id  BIGINT,
    celular_destino     CHAR(9),
    tipo_op_cod         VARCHAR(12)   NOT NULL,
    moneda_cod          CHAR(3)       NOT NULL,
    monto               NUMERIC(18,2) NOT NULL,
    estado_cod          VARCHAR(12)   NOT NULL,
    motivo_cod          VARCHAR(20),
    dispositivo_id      BIGINT,
    clave_idempotencia  VARCHAR(64)   NOT NULL,
    mensaje             VARCHAR(80),
    CONSTRAINT pk_transferencia       PRIMARY KEY (transferencia_id, fecha_operacion),
    -- Una tabla particionada SÍ puede tener FK hacia tablas normales (PostgreSQL 12+)
    CONSTRAINT fk_transferencia_orig  FOREIGN KEY (usuario_origen_id)  REFERENCES usuario_billetera (usuario_id),
    CONSTRAINT fk_transferencia_dest  FOREIGN KEY (usuario_destino_id) REFERENCES usuario_billetera (usuario_id),
    CONSTRAINT fk_transferencia_disp  FOREIGN KEY (dispositivo_id)     REFERENCES dispositivo (dispositivo_id),
    CONSTRAINT fk_transferencia_est   FOREIGN KEY (estado_cod)         REFERENCES cat_estado_transferencia (estado_cod),
    CONSTRAINT fk_transferencia_mot   FOREIGN KEY (motivo_cod)         REFERENCES cat_motivo_rechazo (motivo_cod),
    CONSTRAINT fk_transferencia_tipo  FOREIGN KEY (tipo_op_cod)        REFERENCES cat_tipo_operacion (tipo_op_cod),
    CONSTRAINT fk_transferencia_mon   FOREIGN KEY (moneda_cod)         REFERENCES cat_moneda (moneda_cod),
    CONSTRAINT ck_transferencia_monto CHECK (monto > 0),
    CONSTRAINT ck_transferencia_dest  CHECK (usuario_destino_id IS NOT NULL OR celular_destino IS NOT NULL),
    CONSTRAINT ck_transferencia_no_self CHECK (usuario_destino_id IS NULL
                                            OR usuario_destino_id <> usuario_origen_id),
    CONSTRAINT ck_transferencia_motivo CHECK (
        (estado_cod = 'RECHAZADA' AND motivo_cod IS NOT NULL)
     OR (estado_cod <> 'RECHAZADA' AND motivo_cod IS NULL))
) PARTITION BY RANGE (fecha_operacion);

COMMENT ON TABLE transferencia IS
    'Particionada por mes. La PK incluye fecha_operacion porque PostgreSQL lo exige.';
COMMENT ON CONSTRAINT ck_transferencia_no_self ON transferencia IS
    'Nadie se transfiere a si mismo: patron tipico de prueba de fraude o de error de la app.';

CREATE TABLE transferencia_2026_07 PARTITION OF transferencia
    FOR VALUES FROM ('2026-07-01') TO ('2026-08-01');
CREATE TABLE transferencia_2026_08 PARTITION OF transferencia
    FOR VALUES FROM ('2026-08-01') TO ('2026-09-01');
CREATE TABLE transferencia_2026_09 PARTITION OF transferencia
    FOR VALUES FROM ('2026-09-01') TO ('2026-10-01');
-- Partición por defecto: recibe lo que no encaja. Evita que una carga falle por completo,
-- pero debe monitorearse: si crece, significa que falta crear particiones.
CREATE TABLE transferencia_default PARTITION OF transferencia DEFAULT;

-- =====================================================================================
-- 6. LIBRO MAYOR DE LA BILLETERA (también particionado)
--    Partida doble: una transferencia exitosa genera exactamente DOS movimientos.
-- =====================================================================================

CREATE TABLE movimiento_billetera (
    movimiento_id      BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    fecha_operacion    TIMESTAMP     NOT NULL,
    usuario_id         BIGINT        NOT NULL,
    transferencia_id   BIGINT,
    tipo_op_cod        VARCHAR(12)   NOT NULL,
    moneda_cod         CHAR(3)       NOT NULL,
    monto              NUMERIC(18,2) NOT NULL,
    monto_con_signo    NUMERIC(18,2) NOT NULL,
    CONSTRAINT pk_movimiento_billetera PRIMARY KEY (movimiento_id, fecha_operacion),
    CONSTRAINT fk_mov_billetera_usr    FOREIGN KEY (usuario_id)  REFERENCES usuario_billetera (usuario_id),
    CONSTRAINT fk_mov_billetera_tipo   FOREIGN KEY (tipo_op_cod) REFERENCES cat_tipo_operacion (tipo_op_cod),
    CONSTRAINT fk_mov_billetera_mon    FOREIGN KEY (moneda_cod)  REFERENCES cat_moneda (moneda_cod),
    CONSTRAINT ck_mov_billetera_monto  CHECK (monto > 0),
    CONSTRAINT ck_mov_billetera_signo  CHECK (ABS(monto_con_signo) = monto)
) PARTITION BY RANGE (fecha_operacion);

CREATE TABLE movimiento_billetera_2026_07 PARTITION OF movimiento_billetera
    FOR VALUES FROM ('2026-07-01') TO ('2026-08-01');
CREATE TABLE movimiento_billetera_2026_08 PARTITION OF movimiento_billetera
    FOR VALUES FROM ('2026-08-01') TO ('2026-09-01');
CREATE TABLE movimiento_billetera_2026_09 PARTITION OF movimiento_billetera
    FOR VALUES FROM ('2026-09-01') TO ('2026-10-01');
CREATE TABLE movimiento_billetera_default PARTITION OF movimiento_billetera DEFAULT;

CREATE TABLE saldo_billetera (
    usuario_id      BIGINT        NOT NULL,
    moneda_cod      CHAR(3)       NOT NULL,
    saldo           NUMERIC(18,2) NOT NULL DEFAULT 0,
    fecha_hora_actualizacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_saldo_billetera   PRIMARY KEY (usuario_id, moneda_cod),
    CONSTRAINT fk_saldo_billetera_u FOREIGN KEY (usuario_id) REFERENCES usuario_billetera (usuario_id),
    CONSTRAINT fk_saldo_billetera_m FOREIGN KEY (moneda_cod) REFERENCES cat_moneda (moneda_cod),
    CONSTRAINT ck_saldo_billetera   CHECK (saldo >= 0)
);
COMMENT ON CONSTRAINT ck_saldo_billetera ON saldo_billetera IS
    'Una billetera NUNCA puede quedar en negativo: no es una linea de credito.';

-- =====================================================================================
-- 7. ÍNDICES
--    En tablas particionadas, el indice se crea sobre la tabla padre y PostgreSQL lo
--    propaga a cada particion.
-- =====================================================================================

CREATE INDEX ix_transf_origen  ON transferencia (usuario_origen_id, fecha_operacion);
CREATE INDEX ix_transf_destino ON transferencia (usuario_destino_id, fecha_operacion);
CREATE INDEX ix_transf_estado  ON transferencia (estado_cod);
CREATE INDEX ix_mov_usuario    ON movimiento_billetera (usuario_id, fecha_operacion);
CREATE INDEX ix_mov_transf     ON movimiento_billetera (transferencia_id);
CREATE INDEX ix_idem_transf    ON idempotencia (transferencia_id);

-- =====================================================================================
-- 8. VISTAS
-- =====================================================================================

CREATE VIEW vw_actividad_diaria AS
SELECT  t.fecha_operacion::DATE                                    AS dia,
        COUNT(*)                                                   AS operaciones,
        COUNT(*) FILTER (WHERE t.estado_cod = 'CONFIRMADA')        AS exitosas,
        COUNT(*) FILTER (WHERE t.estado_cod = 'RECHAZADA')         AS rechazadas,
        COUNT(DISTINCT t.usuario_origen_id)                        AS usuarios_activos,
        SUM(t.monto) FILTER (WHERE t.estado_cod = 'CONFIRMADA')    AS monto_transado,
        ROUND(AVG(t.monto) FILTER (WHERE t.estado_cod = 'CONFIRMADA'), 2) AS ticket_promedio
FROM    transferencia t
GROUP BY t.fecha_operacion::DATE;

COMMENT ON VIEW vw_actividad_diaria IS 'Pulso diario del producto: volumen, exito y ticket.';
