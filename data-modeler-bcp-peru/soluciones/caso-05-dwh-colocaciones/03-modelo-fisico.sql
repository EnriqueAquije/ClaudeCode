-- =====================================================================================
-- CASO 05 - Data warehouse dimensional (Kimball): captaciones y colocaciones
-- Modelo FÍSICO - PostgreSQL 14+
-- =====================================================================================
-- REQUISITO: los esquemas caso01 y caso02 deben existir y estar cargados.
-- Este DWH se construye SOBRE ellos, como ocurre en la realidad: el modelo analítico
-- nunca nace de la nada, nace de sistemas transaccionales que ya existen.
-- =====================================================================================

DROP SCHEMA IF EXISTS caso05 CASCADE;
CREATE SCHEMA caso05;
SET search_path TO caso05;

-- =====================================================================================
-- 1. DIMENSIONES
--    Convención Kimball aplicada:
--      - Toda dimensión tiene una CLAVE SUSTITUTA (_sk) y conserva su clave natural.
--      - Toda dimensión tiene una fila "DESCONOCIDO" con sk = -1, para que ningún hecho
--        quede huérfano ni se pierda por un JOIN interno.
-- =====================================================================================

CREATE TABLE dim_tiempo (
    tiempo_sk        INTEGER      NOT NULL,   -- formato AAAAMMDD, clave inteligente
    fecha            DATE         NOT NULL,
    anio             SMALLINT     NOT NULL,
    trimestre        SMALLINT     NOT NULL,
    mes              SMALLINT     NOT NULL,
    nombre_mes       VARCHAR(12)  NOT NULL,
    dia              SMALLINT     NOT NULL,
    dia_semana       SMALLINT     NOT NULL,
    nombre_dia       VARCHAR(12)  NOT NULL,
    periodo          CHAR(6)      NOT NULL,   -- AAAAMM
    es_fin_semana    BOOLEAN      NOT NULL,
    es_fin_mes       BOOLEAN      NOT NULL,
    CONSTRAINT pk_dim_tiempo PRIMARY KEY (tiempo_sk),
    CONSTRAINT uq_dim_tiempo_fecha UNIQUE (fecha)
);
COMMENT ON COLUMN dim_tiempo.tiempo_sk IS
    'Clave inteligente AAAAMMDD: legible en los hechos y ordenable sin JOIN.';

CREATE TABLE dim_ubigeo (
    ubigeo_sk    INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    ubigeo       CHAR(6)      NOT NULL,
    departamento VARCHAR(40)  NOT NULL,
    provincia    VARCHAR(40)  NOT NULL,
    distrito     VARCHAR(40)  NOT NULL,
    macro_region VARCHAR(20)  NOT NULL,
    CONSTRAINT pk_dim_ubigeo PRIMARY KEY (ubigeo_sk),
    CONSTRAINT uq_dim_ubigeo UNIQUE (ubigeo)
);

CREATE TABLE dim_oficina (
    oficina_sk     INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    oficina_cod    VARCHAR(10)  NOT NULL,
    oficina_nombre VARCHAR(80)  NOT NULL,
    ubigeo_sk      INTEGER      NOT NULL,
    fecha_apertura DATE,
    CONSTRAINT pk_dim_oficina        PRIMARY KEY (oficina_sk),
    CONSTRAINT uq_dim_oficina_cod    UNIQUE (oficina_cod),
    CONSTRAINT fk_dim_oficina_ubigeo FOREIGN KEY (ubigeo_sk) REFERENCES dim_ubigeo (ubigeo_sk)
);

-- Dimensión CONFORMADA de producto: unifica pasivos (captaciones) y activos (colocaciones)
-- bajo una sola jerarquía. Es lo que permite comparar ambos negocios en un mismo tablero.
CREATE TABLE dim_producto (
    producto_sk      INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    producto_cod     VARCHAR(20)  NOT NULL,
    producto_nombre  VARCHAR(80)  NOT NULL,
    familia_cod      VARCHAR(20)  NOT NULL,
    negocio_cod      VARCHAR(15)  NOT NULL,   -- CAPTACION / COLOCACION
    moneda_cod       CHAR(3)      NOT NULL,
    CONSTRAINT pk_dim_producto      PRIMARY KEY (producto_sk),
    CONSTRAINT uq_dim_producto_cod  UNIQUE (producto_cod),
    CONSTRAINT ck_dim_producto_neg  CHECK (negocio_cod IN ('CAPTACION','COLOCACION','NO_APLICA'))
);
COMMENT ON TABLE dim_producto IS
    'Dimension CONFORMADA: la misma jerarquia sirve a los hechos de captacion y de colocacion.';

CREATE TABLE dim_canal (
    canal_sk      INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    canal_cod     VARCHAR(10)  NOT NULL,
    canal_desc    VARCHAR(50)  NOT NULL,
    es_presencial BOOLEAN      NOT NULL,
    es_digital    BOOLEAN      NOT NULL,
    CONSTRAINT pk_dim_canal     PRIMARY KEY (canal_sk),
    CONSTRAINT uq_dim_canal_cod UNIQUE (canal_cod)
);

-- DIMENSIÓN LENTAMENTE CAMBIANTE TIPO 2
-- Cada cambio de segmento genera una fila nueva; la anterior se cierra.
CREATE TABLE dim_cliente (
    cliente_sk        BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    cliente_id_origen BIGINT       NOT NULL,   -- id en el sistema de origen (linaje)
    sistema_origen    VARCHAR(20)  NOT NULL,   -- de que sistema vino (linaje)
    tipo_doc_cod      CHAR(2)      NOT NULL,
    num_doc           VARCHAR(20)  NOT NULL,
    nombre_completo   VARCHAR(160) NOT NULL,
    rango_edad        VARCHAR(12)  NOT NULL,
    segmento_cod      VARCHAR(15)  NOT NULL,   -- atributo que CAMBIA -> motiva el SCD2
    ubigeo_sk         INTEGER      NOT NULL,
    fecha_alta        DATE,
    fecha_desde       DATE         NOT NULL,
    fecha_hasta       DATE         NOT NULL DEFAULT DATE '9999-12-31',
    es_vigente        BOOLEAN      NOT NULL DEFAULT TRUE,
    version           SMALLINT     NOT NULL DEFAULT 1,
    CONSTRAINT pk_dim_cliente        PRIMARY KEY (cliente_sk),
    CONSTRAINT fk_dim_cliente_ubigeo FOREIGN KEY (ubigeo_sk) REFERENCES dim_ubigeo (ubigeo_sk),
    CONSTRAINT ck_dim_cliente_vig    CHECK (fecha_hasta >= fecha_desde),
    CONSTRAINT ck_dim_cliente_seg    CHECK (segmento_cod IN ('MASIVO','CONSUMO','PREFERENTE','BANCA_EXCLUSIVA','DESCONOCIDO'))
);
COMMENT ON TABLE dim_cliente IS
    'SCD tipo 2. La misma persona puede tener varias filas (cliente_sk distintos) con vigencias.';

-- Regla del SCD2: una sola version vigente por CLAVE NATURAL DE NEGOCIO.
-- La clave natural es el documento, no el id del sistema origen: el mismo documento
-- puede venir de dos sistemas distintos (core de captaciones y core de creditos).
CREATE UNIQUE INDEX uq_dim_cliente_vigente
    ON dim_cliente (tipo_doc_cod, num_doc) WHERE es_vigente;

-- =====================================================================================
-- 2. TABLAS DE HECHOS
--    Tres tipos distintos, a propósito:
--      - fact_movimiento          -> TRANSACCIONAL  (una fila por evento)
--      - fact_saldo_captacion_mes -> SNAPSHOT PERIÓDICO (una fila por cuenta y mes)
--      - fact_colocacion_mes      -> SNAPSHOT PERIÓDICO (una fila por deudor y mes)
-- =====================================================================================

CREATE TABLE fact_movimiento (
    movimiento_sk     BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    tiempo_sk         INTEGER       NOT NULL,
    cliente_sk        BIGINT        NOT NULL,
    producto_sk       INTEGER       NOT NULL,
    oficina_sk        INTEGER       NOT NULL,
    canal_sk          INTEGER       NOT NULL,
    -- Dimensión degenerada: el número de operación no tiene atributos propios,
    -- pero se conserva en el hecho para poder rastrear hasta el origen.
    num_operacion     VARCHAR(30)   NOT NULL,
    tipo_mov_cod      VARCHAR(10)   NOT NULL,
    -- Medidas
    monto             NUMERIC(18,2) NOT NULL,
    monto_con_signo   NUMERIC(18,2) NOT NULL,
    cantidad_mov      INTEGER       NOT NULL DEFAULT 1,
    CONSTRAINT pk_fact_movimiento      PRIMARY KEY (movimiento_sk),
    CONSTRAINT fk_fact_mov_tiempo      FOREIGN KEY (tiempo_sk)   REFERENCES dim_tiempo (tiempo_sk),
    CONSTRAINT fk_fact_mov_cliente     FOREIGN KEY (cliente_sk)  REFERENCES dim_cliente (cliente_sk),
    CONSTRAINT fk_fact_mov_producto    FOREIGN KEY (producto_sk) REFERENCES dim_producto (producto_sk),
    CONSTRAINT fk_fact_mov_oficina     FOREIGN KEY (oficina_sk)  REFERENCES dim_oficina (oficina_sk),
    CONSTRAINT fk_fact_mov_canal       FOREIGN KEY (canal_sk)    REFERENCES dim_canal (canal_sk),
    CONSTRAINT ck_fact_mov_monto       CHECK (monto > 0),
    CONSTRAINT uq_fact_mov_operacion   UNIQUE (num_operacion)
);
COMMENT ON TABLE fact_movimiento IS
    'Hecho TRANSACCIONAL. Grano: un movimiento de cuenta. Medidas aditivas.';
COMMENT ON COLUMN fact_movimiento.num_operacion IS
    'DIMENSION DEGENERADA: identificador del origen sin atributos propios.';

CREATE TABLE fact_saldo_captacion_mes (
    tiempo_sk         INTEGER       NOT NULL,   -- último día del mes
    cliente_sk        BIGINT        NOT NULL,
    producto_sk       INTEGER       NOT NULL,
    oficina_sk        INTEGER       NOT NULL,
    cuenta_id_origen  BIGINT        NOT NULL,   -- dimensión degenerada
    -- Medidas
    saldo_fin_mes     NUMERIC(18,2) NOT NULL,
    saldo_promedio    NUMERIC(18,2) NOT NULL,
    cant_movimientos  INTEGER       NOT NULL,
    monto_abonos      NUMERIC(18,2) NOT NULL,
    monto_cargos      NUMERIC(18,2) NOT NULL,
    CONSTRAINT pk_fact_saldo_cap       PRIMARY KEY (tiempo_sk, cuenta_id_origen),
    CONSTRAINT fk_fact_saldo_tiempo    FOREIGN KEY (tiempo_sk)   REFERENCES dim_tiempo (tiempo_sk),
    CONSTRAINT fk_fact_saldo_cliente   FOREIGN KEY (cliente_sk)  REFERENCES dim_cliente (cliente_sk),
    CONSTRAINT fk_fact_saldo_producto  FOREIGN KEY (producto_sk) REFERENCES dim_producto (producto_sk),
    CONSTRAINT fk_fact_saldo_oficina   FOREIGN KEY (oficina_sk)  REFERENCES dim_oficina (oficina_sk)
);
COMMENT ON TABLE fact_saldo_captacion_mes IS
    'Hecho SNAPSHOT PERIODICO. Grano: cuenta-mes. OJO: saldo_fin_mes es SEMIADITIVA '
    '(se suma entre cuentas, NO se suma entre meses).';
COMMENT ON COLUMN fact_saldo_captacion_mes.saldo_fin_mes IS
    'MEDIDA SEMIADITIVA: sumarla a lo largo del tiempo produce un numero sin significado.';

CREATE TABLE fact_colocacion_mes (
    tiempo_sk         INTEGER       NOT NULL,
    cliente_sk        BIGINT        NOT NULL,
    producto_sk       INTEGER       NOT NULL,
    deudor_id_origen  BIGINT        NOT NULL,
    clasificacion_cod CHAR(1)       NOT NULL,
    dias_atraso       INTEGER       NOT NULL,
    -- Medidas
    saldo_capital     NUMERIC(18,2) NOT NULL,
    monto_provision   NUMERIC(18,2) NOT NULL,
    cant_creditos     INTEGER       NOT NULL DEFAULT 1,
    CONSTRAINT pk_fact_colocacion       PRIMARY KEY (tiempo_sk, deudor_id_origen),
    CONSTRAINT fk_fact_coloc_tiempo     FOREIGN KEY (tiempo_sk)   REFERENCES dim_tiempo (tiempo_sk),
    CONSTRAINT fk_fact_coloc_cliente    FOREIGN KEY (cliente_sk)  REFERENCES dim_cliente (cliente_sk),
    CONSTRAINT fk_fact_coloc_producto   FOREIGN KEY (producto_sk) REFERENCES dim_producto (producto_sk),
    CONSTRAINT ck_fact_coloc_clasif     CHECK (clasificacion_cod IN ('0','1','2','3','4'))
);
COMMENT ON TABLE fact_colocacion_mes IS
    'Hecho SNAPSHOT PERIODICO. Grano: deudor-mes. Alimenta el reporte regulatorio (caso 10).';

-- =====================================================================================
-- 3. ÍNDICES DEL DWH
--    En un modelo estrella se indexan las FK a dimensiones: son el camino de todo JOIN.
-- =====================================================================================

CREATE INDEX ix_fact_mov_tiempo    ON fact_movimiento (tiempo_sk);
CREATE INDEX ix_fact_mov_cliente   ON fact_movimiento (cliente_sk);
CREATE INDEX ix_fact_mov_producto  ON fact_movimiento (producto_sk);
CREATE INDEX ix_fact_mov_canal     ON fact_movimiento (canal_sk);
CREATE INDEX ix_fact_saldo_cliente ON fact_saldo_captacion_mes (cliente_sk);
CREATE INDEX ix_fact_saldo_prod    ON fact_saldo_captacion_mes (producto_sk);
CREATE INDEX ix_fact_coloc_cliente ON fact_colocacion_mes (cliente_sk);
CREATE INDEX ix_dim_cliente_nat    ON dim_cliente (tipo_doc_cod, num_doc, fecha_desde);

-- =====================================================================================
-- 4. VISTAS DE CONSUMO (la capa que ve el usuario de negocio)
-- =====================================================================================

CREATE VIEW vw_captacion_mensual AS
SELECT  t.periodo,
        t.anio,
        t.mes,
        p.negocio_cod,
        p.familia_cod,
        p.producto_nombre,
        p.moneda_cod,
        u.departamento,
        u.macro_region,
        c.segmento_cod,
        COUNT(*)                        AS cant_cuentas,
        SUM(f.saldo_fin_mes)            AS saldo_fin_mes,
        SUM(f.saldo_promedio)           AS saldo_promedio,
        SUM(f.cant_movimientos)         AS cant_movimientos
FROM    fact_saldo_captacion_mes f
JOIN    dim_tiempo   t ON t.tiempo_sk   = f.tiempo_sk
JOIN    dim_producto p ON p.producto_sk = f.producto_sk
JOIN    dim_cliente  c ON c.cliente_sk  = f.cliente_sk
JOIN    dim_oficina  o ON o.oficina_sk  = f.oficina_sk
JOIN    dim_ubigeo   u ON u.ubigeo_sk   = o.ubigeo_sk
GROUP BY t.periodo, t.anio, t.mes, p.negocio_cod, p.familia_cod, p.producto_nombre,
         p.moneda_cod, u.departamento, u.macro_region, c.segmento_cod;

COMMENT ON VIEW vw_captacion_mensual IS
    'Capa semantica de captaciones: el usuario de negocio no escribe JOINs.';

CREATE VIEW vw_colocacion_mensual AS
SELECT  t.periodo,
        t.anio,
        t.mes,
        c.segmento_cod,
        u.departamento,
        f.clasificacion_cod,
        CASE f.clasificacion_cod
            WHEN '0' THEN 'Normal' WHEN '1' THEN 'CPP' WHEN '2' THEN 'Deficiente'
            WHEN '3' THEN 'Dudoso' ELSE 'Perdida' END AS clasificacion_desc,
        COUNT(*)                     AS cant_deudores,
        SUM(f.saldo_capital)         AS saldo_capital,
        SUM(f.monto_provision)       AS provision,
        ROUND(AVG(f.dias_atraso), 1) AS dias_atraso_promedio
FROM    fact_colocacion_mes f
JOIN    dim_tiempo  t ON t.tiempo_sk  = f.tiempo_sk
JOIN    dim_cliente c ON c.cliente_sk = f.cliente_sk
JOIN    dim_ubigeo  u ON u.ubigeo_sk  = c.ubigeo_sk
GROUP BY t.periodo, t.anio, t.mes, c.segmento_cod, u.departamento, f.clasificacion_cod;
