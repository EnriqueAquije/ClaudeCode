-- =====================================================================================
-- 5. FUNCIÓN DE CLASIFICACIÓN PARAMETRIZADA
--    La regla normativa NO se escribe en el código de la aplicación: se lee de la tabla
--    de parámetros vigente a la fecha de corte.
-- =====================================================================================

CREATE FUNCTION fn_clasificar(p_tipo_credito CHAR(1), p_dias INTEGER, p_fecha DATE)
RETURNS CHAR(1)
LANGUAGE sql STABLE AS $$
    SELECT p.clasificacion_cod
    FROM   par_clasificacion_dias p
    WHERE  p.tipo_credito_cod = p_tipo_credito
      AND  p_dias BETWEEN p.dias_desde AND p.dias_hasta
      AND  p_fecha BETWEEN p.fecha_desde AND p.fecha_hasta
    LIMIT 1;
$$;
COMMENT ON FUNCTION fn_clasificar IS
    'Devuelve la categoria SBS segun dias de atraso, tipo de credito y fecha de vigencia de la norma.';

CREATE VIEW vw_credito_detalle AS
SELECT  c.credito_id,
        c.num_credito,
        d.deudor_id,
        d.tipo_doc_cod,
        d.num_doc,
        d.ape_paterno || ', ' || d.nombres AS deudor_nombre,
        tc.tipo_credito_desc,
        c.moneda_cod,
        c.monto_desembolsado,
        c.tea_pct,
        c.plazo_meses,
        c.fecha_desembolso,
        c.estado_credito,
        s.canal_cod,
        e.score,
        e.ratio_cuota_ingreso
FROM    credito           c
JOIN    deudor            d  ON d.deudor_id        = c.deudor_id
JOIN    cat_tipo_credito  tc ON tc.tipo_credito_cod = c.tipo_credito_cod
JOIN    solicitud_credito s  ON s.solicitud_id     = c.solicitud_id
LEFT JOIN evaluacion_crediticia e ON e.solicitud_id = s.solicitud_id;
