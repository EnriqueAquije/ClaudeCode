DROP SCHEMA IF EXISTS caso02 CASCADE;
CREATE SCHEMA caso02;
SET search_path TO caso02;

-- =====================================================================================
-- 1. CATÁLOGOS REGULATORIOS
--    Dominios impuestos por la Resolución SBS N.º 11356-2008. NUNCA texto libre.
-- =====================================================================================

CREATE TABLE cat_moneda (
    moneda_cod  CHAR(3)     NOT NULL,
    moneda_desc VARCHAR(50) NOT NULL,
    CONSTRAINT pk_cat_moneda PRIMARY KEY (moneda_cod)
);

CREATE TABLE cat_tipo_documento (
    tipo_doc_cod  CHAR(2)     NOT NULL,
    tipo_doc_desc VARCHAR(40) NOT NULL,
    CONSTRAINT pk_cat_tipo_documento PRIMARY KEY (tipo_doc_cod)
);

-- Los 8 tipos de crédito de la Res. SBS 11356-2008
CREATE TABLE cat_tipo_credito (
    tipo_credito_cod  CHAR(1)     NOT NULL,
    tipo_credito_desc VARCHAR(60) NOT NULL,
    es_minorista      BOOLEAN     NOT NULL,
    CONSTRAINT pk_cat_tipo_credito PRIMARY KEY (tipo_credito_cod)
);
COMMENT ON TABLE cat_tipo_credito IS 'Tipos de crédito segun Res. SBS 11356-2008. Dominio cerrado.';

-- Las 5 categorías de clasificación del deudor
CREATE TABLE cat_clasificacion (
    clasificacion_cod  CHAR(1)     NOT NULL,
    clasificacion_desc VARCHAR(40) NOT NULL,
    orden_riesgo       SMALLINT    NOT NULL,
    CONSTRAINT pk_cat_clasificacion  PRIMARY KEY (clasificacion_cod),
    CONSTRAINT uq_cat_clasif_orden   UNIQUE (orden_riesgo)
);
COMMENT ON TABLE cat_clasificacion IS
    '0=Normal 1=CPP 2=Deficiente 3=Dudoso 4=Perdida (Res. SBS 11356-2008).';

CREATE TABLE cat_estado_solicitud (
    estado_sol_cod  VARCHAR(12) NOT NULL,
    estado_sol_desc VARCHAR(50) NOT NULL,
    es_final        BOOLEAN     NOT NULL,
    CONSTRAINT pk_cat_estado_solicitud PRIMARY KEY (estado_sol_cod)
);

CREATE TABLE cat_motivo_rechazo (
    motivo_cod  VARCHAR(15) NOT NULL,
    motivo_desc VARCHAR(80) NOT NULL,
    CONSTRAINT pk_cat_motivo_rechazo PRIMARY KEY (motivo_cod)
);

CREATE TABLE cat_canal_venta (
    canal_cod  VARCHAR(10) NOT NULL,
    canal_desc VARCHAR(50) NOT NULL,
    es_digital BOOLEAN     NOT NULL,
    CONSTRAINT pk_cat_canal_venta PRIMARY KEY (canal_cod)
);

-- =====================================================================================
-- 2. PARÁMETROS NORMATIVOS VIGENTES POR FECHA
--    PATRÓN CLAVE DEL CASO: cuando la SBS cambia un tramo, es un INSERT, no un cambio
--    de modelo ni de código.
-- =====================================================================================

CREATE TABLE par_clasificacion_dias (
    tipo_credito_cod  CHAR(1)     NOT NULL,
    clasificacion_cod CHAR(1)     NOT NULL,
    dias_desde        INTEGER     NOT NULL,
    dias_hasta        INTEGER     NOT NULL,
    fecha_desde       DATE        NOT NULL,
    fecha_hasta       DATE        NOT NULL DEFAULT DATE '9999-12-31',
    base_legal        VARCHAR(120),
    CONSTRAINT pk_par_clasif_dias   PRIMARY KEY (tipo_credito_cod, clasificacion_cod, fecha_desde),
    CONSTRAINT fk_par_clasif_tipo   FOREIGN KEY (tipo_credito_cod)  REFERENCES cat_tipo_credito (tipo_credito_cod),
    CONSTRAINT fk_par_clasif_clas   FOREIGN KEY (clasificacion_cod) REFERENCES cat_clasificacion (clasificacion_cod),
    CONSTRAINT ck_par_clasif_rango  CHECK (dias_hasta >= dias_desde),
    CONSTRAINT ck_par_clasif_vig    CHECK (fecha_hasta >= fecha_desde)
);
COMMENT ON TABLE par_clasificacion_dias IS
    'Tramos de dias de atraso por tipo de credito. REFERENCIAL: verificar norma vigente en sbs.gob.pe.';

CREATE TABLE par_provision (
    clasificacion_cod CHAR(1)       NOT NULL,
    tiene_garantia    BOOLEAN       NOT NULL,
    tasa_provision    NUMERIC(9,6)  NOT NULL,
    fecha_desde       DATE          NOT NULL,
    fecha_hasta       DATE          NOT NULL DEFAULT DATE '9999-12-31',
    base_legal        VARCHAR(120),
    CONSTRAINT pk_par_provision    PRIMARY KEY (clasificacion_cod, tiene_garantia, fecha_desde),
    CONSTRAINT fk_par_prov_clasif  FOREIGN KEY (clasificacion_cod) REFERENCES cat_clasificacion (clasificacion_cod),
    CONSTRAINT ck_par_prov_tasa    CHECK (tasa_provision >= 0 AND tasa_provision <= 1)
);
COMMENT ON TABLE par_provision IS
    'Tasas de provision por categoria. REFERENCIAL con fines educativos.';

-- =====================================================================================
-- 3. ENTIDADES
-- =====================================================================================

CREATE TABLE deudor (
    deudor_id        BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    tipo_doc_cod     CHAR(2)      NOT NULL,
    num_doc          VARCHAR(20)  NOT NULL,
    ape_paterno      VARCHAR(60)  NOT NULL,
    ape_materno      VARCHAR(60),
    nombres          VARCHAR(80)  NOT NULL,
    fecha_nacimiento DATE,
    ingreso_declarado NUMERIC(18,2),
    situacion_laboral VARCHAR(20),
    antiguedad_meses  INTEGER,
    fecha_alta       DATE         NOT NULL,
    CONSTRAINT pk_deudor          PRIMARY KEY (deudor_id),
    CONSTRAINT uq_deudor_doc      UNIQUE (tipo_doc_cod, num_doc),
    CONSTRAINT fk_deudor_tipo_doc FOREIGN KEY (tipo_doc_cod) REFERENCES cat_tipo_documento (tipo_doc_cod),
    CONSTRAINT ck_deudor_sit_lab  CHECK (situacion_laboral IN ('DEPENDIENTE','INDEPENDIENTE','PENSIONISTA')),
    CONSTRAINT ck_deudor_ingreso  CHECK (ingreso_declarado IS NULL OR ingreso_declarado >= 0)
);
COMMENT ON TABLE deudor IS 'Persona que solicita u obtiene crédito. CONTIENE DATOS PERSONALES.';
COMMENT ON COLUMN deudor.ingreso_declarado IS 'DATO SENSIBLE (ingresos economicos, Ley 29733).';

CREATE TABLE solicitud_credito (
    solicitud_id       BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    num_solicitud      VARCHAR(20)   NOT NULL,
    deudor_id          BIGINT        NOT NULL,
    tipo_credito_cod   CHAR(1)       NOT NULL,
    moneda_cod         CHAR(3)       NOT NULL,
    canal_cod          VARCHAR(10)   NOT NULL,
    monto_solicitado   NUMERIC(18,2) NOT NULL,
    plazo_meses        INTEGER       NOT NULL,
    proposito_cod      VARCHAR(20)   NOT NULL,
    fecha_solicitud    DATE          NOT NULL,
    estado_sol_cod     VARCHAR(12)   NOT NULL,
    fecha_estado       DATE          NOT NULL,
    motivo_cod         VARCHAR(15),
    CONSTRAINT pk_solicitud          PRIMARY KEY (solicitud_id),
    CONSTRAINT uq_solicitud_num      UNIQUE (num_solicitud),
    CONSTRAINT fk_solicitud_deudor   FOREIGN KEY (deudor_id)        REFERENCES deudor (deudor_id),
    CONSTRAINT fk_solicitud_tipo     FOREIGN KEY (tipo_credito_cod) REFERENCES cat_tipo_credito (tipo_credito_cod),
    CONSTRAINT fk_solicitud_moneda   FOREIGN KEY (moneda_cod)       REFERENCES cat_moneda (moneda_cod),
    CONSTRAINT fk_solicitud_canal    FOREIGN KEY (canal_cod)        REFERENCES cat_canal_venta (canal_cod),
    CONSTRAINT fk_solicitud_estado   FOREIGN KEY (estado_sol_cod)   REFERENCES cat_estado_solicitud (estado_sol_cod),
    CONSTRAINT fk_solicitud_motivo   FOREIGN KEY (motivo_cod)       REFERENCES cat_motivo_rechazo (motivo_cod),
    CONSTRAINT ck_solicitud_monto    CHECK (monto_solicitado > 0),
    CONSTRAINT ck_solicitud_plazo    CHECK (plazo_meses BETWEEN 3 AND 84),
    -- Un rechazo SIEMPRE debe tener motivo; una aprobación nunca lo tiene.
    CONSTRAINT ck_solicitud_motivo_coherente CHECK (
        (estado_sol_cod = 'RECHAZADA' AND motivo_cod IS NOT NULL)
     OR (estado_sol_cod <> 'RECHAZADA' AND motivo_cod IS NULL))
);

-- Máquina de estados: la historia del trámite, no solo su estado actual.
CREATE TABLE solicitud_estado_hist (
    solicitud_id    BIGINT      NOT NULL,
    secuencia       SMALLINT    NOT NULL,
    estado_sol_cod  VARCHAR(12) NOT NULL,
    fecha_hora      TIMESTAMP   NOT NULL,
    usuario         VARCHAR(40) NOT NULL,
    CONSTRAINT pk_solicitud_hist     PRIMARY KEY (solicitud_id, secuencia),
    CONSTRAINT fk_solicitud_hist_sol FOREIGN KEY (solicitud_id)   REFERENCES solicitud_credito (solicitud_id),
    CONSTRAINT fk_solicitud_hist_est FOREIGN KEY (estado_sol_cod) REFERENCES cat_estado_solicitud (estado_sol_cod)
);

CREATE TABLE evaluacion_crediticia (
    evaluacion_id        BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    solicitud_id         BIGINT        NOT NULL,
    fecha_evaluacion     DATE          NOT NULL,
    score                INTEGER       NOT NULL,
    ingreso_verificado   NUMERIC(18,2) NOT NULL,
    deuda_sistema        NUMERIC(18,2) NOT NULL DEFAULT 0,
    cuota_estimada       NUMERIC(18,2) NOT NULL,
    ratio_cuota_ingreso  NUMERIC(9,6)  NOT NULL,
    peor_clasif_sistema  CHAR(1)       NOT NULL,
    resultado            VARCHAR(12)   NOT NULL,
    CONSTRAINT pk_evaluacion        PRIMARY KEY (evaluacion_id),
    CONSTRAINT uq_evaluacion_sol    UNIQUE (solicitud_id),
    CONSTRAINT fk_evaluacion_sol    FOREIGN KEY (solicitud_id)        REFERENCES solicitud_credito (solicitud_id),
    CONSTRAINT fk_evaluacion_clasif FOREIGN KEY (peor_clasif_sistema) REFERENCES cat_clasificacion (clasificacion_cod),
    CONSTRAINT ck_evaluacion_score  CHECK (score BETWEEN 0 AND 1000),
    CONSTRAINT ck_evaluacion_result CHECK (resultado IN ('APROBADO','RECHAZADO')),
    CONSTRAINT ck_evaluacion_ratio  CHECK (ratio_cuota_ingreso >= 0)
);
COMMENT ON COLUMN evaluacion_crediticia.peor_clasif_sistema IS
    'Peor clasificacion del deudor en el sistema financiero (alineamiento, Res. SBS 11356-2008).';

CREATE TABLE credito (
    credito_id        BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    num_credito       VARCHAR(20)   NOT NULL,
    solicitud_id      BIGINT        NOT NULL,
    deudor_id         BIGINT        NOT NULL,
    tipo_credito_cod  CHAR(1)       NOT NULL,
    moneda_cod        CHAR(3)       NOT NULL,
    monto_desembolsado NUMERIC(18,2) NOT NULL,
    tea_pct           NUMERIC(9,6)  NOT NULL,
    plazo_meses       INTEGER       NOT NULL,
    fecha_desembolso  DATE          NOT NULL,
    fecha_vencimiento DATE          NOT NULL,
    estado_credito    VARCHAR(12)   NOT NULL,
    tiene_garantia    BOOLEAN       NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_credito          PRIMARY KEY (credito_id),
    CONSTRAINT uq_credito_num      UNIQUE (num_credito),
    CONSTRAINT uq_credito_sol      UNIQUE (solicitud_id),
    CONSTRAINT fk_credito_sol      FOREIGN KEY (solicitud_id)     REFERENCES solicitud_credito (solicitud_id),
    CONSTRAINT fk_credito_deudor   FOREIGN KEY (deudor_id)        REFERENCES deudor (deudor_id),
    CONSTRAINT fk_credito_tipo     FOREIGN KEY (tipo_credito_cod) REFERENCES cat_tipo_credito (tipo_credito_cod),
    CONSTRAINT fk_credito_moneda   FOREIGN KEY (moneda_cod)       REFERENCES cat_moneda (moneda_cod),
    CONSTRAINT ck_credito_monto    CHECK (monto_desembolsado > 0),
    CONSTRAINT ck_credito_tea      CHECK (tea_pct > 0 AND tea_pct < 3),
    CONSTRAINT ck_credito_estado   CHECK (estado_credito IN ('VIGENTE','CANCELADO','CASTIGADO','REFINANCIADO')),
    CONSTRAINT ck_credito_fechas   CHECK (fecha_vencimiento > fecha_desembolso)
);

CREATE TABLE cronograma_cuota (
    credito_id       BIGINT        NOT NULL,
    num_cuota        SMALLINT      NOT NULL,
    fecha_vencimiento DATE         NOT NULL,
    monto_capital    NUMERIC(18,2) NOT NULL,
    monto_interes    NUMERIC(18,2) NOT NULL,
    monto_seguro     NUMERIC(18,2) NOT NULL DEFAULT 0,
    monto_cuota      NUMERIC(18,2) NOT NULL,
    fecha_pago       DATE,
    monto_pagado     NUMERIC(18,2) NOT NULL DEFAULT 0,
    estado_cuota     VARCHAR(10)   NOT NULL,
    CONSTRAINT pk_cronograma       PRIMARY KEY (credito_id, num_cuota),
    CONSTRAINT fk_cronograma_cred  FOREIGN KEY (credito_id) REFERENCES credito (credito_id),
    CONSTRAINT ck_cronograma_cuota CHECK (monto_cuota = monto_capital + monto_interes + monto_seguro),
    CONSTRAINT ck_cronograma_estado CHECK (estado_cuota IN ('PENDIENTE','PAGADA','VENCIDA')),
    CONSTRAINT ck_cronograma_pago  CHECK (
        (estado_cuota = 'PAGADA' AND fecha_pago IS NOT NULL)
     OR (estado_cuota <> 'PAGADA'))
);
COMMENT ON COLUMN cronograma_cuota.monto_cuota IS 'Cuota total = capital + interes + seguro (CHECK lo garantiza).';

-- Foto mensual del deudor: lo que se reporta a la SBS y permite reconstruir el pasado.
CREATE TABLE deudor_clasificacion_mes (
    deudor_id         BIGINT        NOT NULL,
    periodo           CHAR(6)       NOT NULL,           -- AAAAMM
    fecha_corte       DATE          NOT NULL,
    tipo_credito_cod  CHAR(1)       NOT NULL,
    dias_atraso       INTEGER       NOT NULL,
    clasificacion_cod CHAR(1)       NOT NULL,
    saldo_capital     NUMERIC(18,2) NOT NULL,
    tiene_garantia    BOOLEAN       NOT NULL DEFAULT FALSE,
    tasa_provision    NUMERIC(9,6)  NOT NULL,
    monto_provision   NUMERIC(18,2) NOT NULL,
    CONSTRAINT pk_deudor_clasif_mes   PRIMARY KEY (deudor_id, periodo),
    CONSTRAINT fk_deudor_clasif_deu   FOREIGN KEY (deudor_id)         REFERENCES deudor (deudor_id),
    CONSTRAINT fk_deudor_clasif_tipo  FOREIGN KEY (tipo_credito_cod)  REFERENCES cat_tipo_credito (tipo_credito_cod),
    CONSTRAINT fk_deudor_clasif_clas  FOREIGN KEY (clasificacion_cod) REFERENCES cat_clasificacion (clasificacion_cod),
    CONSTRAINT ck_deudor_clasif_dias  CHECK (dias_atraso >= 0),
    CONSTRAINT ck_deudor_clasif_per   CHECK (periodo ~ '^[0-9]{6}$')
);
COMMENT ON TABLE deudor_clasificacion_mes IS
    'Snapshot mensual por deudor. Grano: deudor-periodo. Base del reporte regulatorio (caso 10).';

