#!/usr/bin/env bash
# =====================================================================================
#  version-minima.sh — ¿qué versión de PostgreSQL exige de verdad este laboratorio?
# =====================================================================================
#  El README dice "PostgreSQL 14 o superior". Esa cifra venía de una impresión, no de
#  una comprobación, y solo se ha EJECUTADO en 16. Este script hace lo segundo mejor:
#  deriva el mínimo de la SINTAXIS realmente usada, buscando construcciones cuya versión
#  de introducción se conoce.
#
#  No sustituye a ejecutar el laboratorio en esa versión. Sí convierte una afirmación
#  en algo que cualquiera puede recalcular cuando el material cambie.
# =====================================================================================

set -uo pipefail
RAIZ="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

if [ -t 1 ]; then VERDE=$'\033[0;32m'; AMAR=$'\033[0;33m'; NEG=$'\033[1m'; FIN=$'\033[0m'
else VERDE=''; AMAR=''; NEG=''; FIN=''; fi

# construccion | version minima | que es
RASGOS=(
  "GENERATED ALWAYS AS \\(|12|Columnas generadas (STORED)"
  "GENERATED BY DEFAULT AS IDENTITY|10|Columnas de identidad"
  "PARTITION BY RANGE|10|Particionamiento declarativo"
  "PARTITION OF .* DEFAULT|11|Particion DEFAULT"
  "RANGE BETWEEN INTERVAL|11|Marcos de ventana RANGE con desplazamiento"
  "FORCE ROW LEVEL SECURITY|9.5|RLS forzado al dueno de la tabla"
  "ON CONFLICT|9.5|Insercion idempotente"
  "FILTER \\(WHERE|9.4|Agregados con filtro"
  "JSONB_BUILD_OBJECT|9.4|Construccion de JSONB"
  "MERGE INTO|15|Sentencia MERGE"
  "ANY_VALUE\\(|16|Agregado ANY_VALUE"
  "JSON_TABLE\\(|17|JSON_TABLE"
)

echo ""
echo "=============================================================="
echo "   VERSION MINIMA DE POSTGRESQL EXIGIDA POR EL LABORATORIO"
echo "=============================================================="
echo ""
printf "  %-46s %-6s %s\n" "CONSTRUCCION" "DESDE" "USOS"
printf "  %-46s %-6s %s\n" "----------------------------------------------" "------" "----"

MAYOR="9.4"
mayor_que() {  # $1 > $2 ?
    [ "$(printf '%s\n%s\n' "$1" "$2" | sort -V | tail -1)" = "$1" ] && [ "$1" != "$2" ]
}

for r in "${RASGOS[@]}"; do
    IFS='|' read -r patron ver desc <<< "${r}"
    N=$(grep -rlE "${patron}" --include=*.sql "${RAIZ}/soluciones" "${RAIZ}/casos" "${RAIZ}/validacion" 2>/dev/null | wc -l | tr -d ' ')
    if [ "${N}" -gt 0 ]; then
        printf "  %-46s %-6s %s\n" "${desc}" "${ver}" "${N} fichero(s)"
        mayor_que "${ver}" "${MAYOR}" && MAYOR="${ver}"
    fi
done

echo ""
echo "  Extensiones requeridas (paquete contrib):"
for e in fuzzystrmatch pg_trgm unaccent; do
    N=$(grep -rl "CREATE EXTENSION IF NOT EXISTS ${e}" --include=*.sql "${RAIZ}/soluciones" 2>/dev/null | wc -l | tr -d ' ')
    [ "${N}" -gt 0 ] && printf "    - %-16s (caso 08)\n" "${e}"
done

echo ""
echo "${NEG}  Mínimo derivado de la sintaxis : PostgreSQL ${MAYOR}${FIN}"
echo "${NEG}  Versión realmente ejecutada    : PostgreSQL 16.13${FIN}"
echo ""
echo "${AMAR}  Entre ${MAYOR} y 16 el laboratorio NO se ha ejecutado. La sintaxis lo admite;"
echo "  eso no es lo mismo que haberlo probado. Si lo corres en una version intermedia"
echo "  y algo falla, es informacion util: reportala.${FIN}"
echo ""
