-- -------------------------------------------------------------------------------------
-- PASO 5 — Transformar y cargar en el modelo
--    Función auxiliar para convertir la fecha del BCRP a DATE.
-- -------------------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION fn_fecha_bcrp(p_texto TEXT)
RETURNS DATE
LANGUAGE sql IMMUTABLE AS $$
    SELECT TO_DATE(
        SPLIT_PART(p_texto, '.', 1) || '-' ||
        CASE LOWER(SPLIT_PART(p_texto, '.', 2))
            WHEN 'ene' THEN '01' WHEN 'feb' THEN '02' WHEN 'mar' THEN '03'
            WHEN 'abr' THEN '04' WHEN 'may' THEN '05' WHEN 'jun' THEN '06'
            WHEN 'jul' THEN '07' WHEN 'ago' THEN '08' WHEN 'set' THEN '09'
            WHEN 'sep' THEN '09' WHEN 'oct' THEN '10' WHEN 'nov' THEN '11'
            WHEN 'dic' THEN '12'
        END || '-20' || SPLIT_PART(p_texto, '.', 3),
        'DD-MM-YYYY');
$$;
COMMENT ON FUNCTION fn_fecha_bcrp IS
    'Convierte el formato de fecha de BCRPData (DD.Mmm.AA) a DATE. Verificar el formato '
    'real del archivo descargado antes de usar.';

